// KeralaLive3PM - Official PWA Service Worker
const CACHE_NAME = 'keralalive-cache-v1';
const PRECACHE_ASSETS = [
  '/',
  '/checker',
  '/chart',
  '/yesterday',
  '/favicon.svg',
  '/manifest.json'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      )
    )
  );
  self.clients.claim();
});

// Network-first strategy: always fetch freshest 3:00 PM live lottery data
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  // Never cache API admin requests or mutations
  if (event.request.url.includes('/api/admin/')) return;

  event.respondWith(
    fetch(event.request)
      .then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200 && networkResponse.type === 'basic') {
          const responseToCache = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(event.request, responseToCache);
          });
        }
        return networkResponse;
      })
      .catch(() => {
        return caches.match(event.request);
      })
  );
});
